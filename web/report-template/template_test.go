package reporttemplate

import (
	"regexp"
	"strings"
	"testing"
)

func TestRender(t *testing.T) {
	out, err := Render(Data{
		Title: "标题 <x>", Summary: "摘要", Markdown: "## 一\n\n事实 [1]，无效引用 [9]。\n\n<script>alert(1)</script>\n",
		Sources: []Source{{Index: 1, URL: "https://a.example/1", Title: "来源一"}, {Index: 2, URL: "mcp://amap/place_search", Title: "高德地图：place_search"}},
	})
	if err != nil {
		t.Fatal(err)
	}
	html := string(out)
	for _, want := range []string{"<h1>标题 &lt;x&gt;</h1>", `<a href="#src-1">1</a>`, "[9]", `id="src-1"`} {
		if !strings.Contains(html, want) {
			t.Errorf("missing %q", want)
		}
	}
	if !strings.Contains(html, `<li id="src-2">高德地图：place_search`) || strings.Contains(html, "ZgotmplZ") {
		t.Error("connector sources must be listed without a link")
	}
	if strings.Contains(html, "<script>alert") {
		t.Error("raw HTML from markdown must not be rendered")
	}
}

func TestRenderEnglish(t *testing.T) {
	out, err := Render(Data{Title: "EV market", Markdown: "Fact [1].", SourceCount: 1, Lang: "en", Share: true,
		Sources: []Source{{Index: 1, URL: "https://a.example/1", Title: "One"}}})
	if err != nil {
		t.Fatal(err)
	}
	html := string(out)
	for _, want := range []string{`<html lang="en">`, "1 sources", "<h2>Sources</h2>", "generated by AI", "Create your own report"} {
		if !strings.Contains(html, want) {
			t.Errorf("missing %q", want)
		}
	}
	if regexp.MustCompile(`\p{Han}`).MatchString(html) {
		t.Error("English page has Chinese text")
	}
}

func TestContentsControlsAreLocalisedIcons(t *testing.T) {
	for _, tc := range []struct{ lang, label string }{{"zh", "目录"}, {"zh-Hant", "目錄"}, {"en", "Table of contents"}} {
		out, err := Render(Data{Lang: tc.lang, Markdown: "## Heading\n\nText."})
		if err != nil {
			t.Fatal(err)
		}
		html := string(out)
		if strings.Count(html, `class="toc-button" type="button" aria-label="`+tc.label+`"`) != 1 || strings.Contains(html, `class="toc-top"`) || strings.Contains(html, `class="toc-hide"`) {
			t.Fatalf("wrong number or label of contents controls for %s", tc.lang)
		}
		if strings.Contains(html, `.has-report .report-content{padding-right:`) {
			t.Fatal("floating directory must not reserve text width")
		}
	}
}
