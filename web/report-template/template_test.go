func TestCSPCoversAllInlineScripts(t *testing.T) {
	spec := visualTestSpec("L2")
	raw, _ := json.Marshal(spec)
	out, err := Render(Data{Markdown: "正文\n\n```zeus-chart\n" + string(raw) + "\n```\n"})
	if err != nil {
		t.Fatal(err)
	}
	html := string(out)
	metaRe := regexp.MustCompile(`(?i)http-equiv="Content-Security-Policy" content="([^"]*)"`)
	meta := metaRe.FindStringSubmatch(html)
	if meta == nil {
		t.Fatal("CSP meta missing")
	}
	csp := stdhtml.UnescapeString(meta[1])
	scriptRe := regexp.MustCompile(`(?s)<script(?: [^>]*)?>(.*?)</script>`)
	for _, m := range scriptRe.FindAllStringSubmatch(html, -1) {
		if strings.Contains(m[0], `type="application/json"`) {
			continue
		}
		sum := sha256.Sum256([]byte(m[1]))
		hash := "'sha256-" + base64.StdEncoding.EncodeToString(sum[:]) + "'"
		if !strings.Contains(csp, hash) {
			t.Fatalf("CSP misses inline script hash %s", hash)
		}
	}
}

