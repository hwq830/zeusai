func TestRenderChartScriptHashAndDataSeparation(t *testing.T) {
	spec := visualTestSpec("L2")
	raw, _ := json.Marshal(spec)
	out, err := Render(Data{Title: "Chart", Markdown: "正文\n\n```zeus-chart\n" + string(raw) + "\n```\n"})
	if err != nil {
		t.Fatal(err)
	}
	html := string(out)
	hash := sha256.Sum256([]byte(visualChartScript))
	want := "script-src 'sha256-" + base64.StdEncoding.EncodeToString(hash[:]) + "'"
	if !strings.Contains(stdhtml.UnescapeString(html), want) {
		t.Fatalf("CSP hash missing: %s", want)
	}
	dataStart := strings.Index(html, `<script type="application/json" id="zeus-chart-data">`)
	if dataStart < 0 {
		t.Fatal("data block missing")
	}
	dataEnd := strings.Index(html[dataStart:], `</script>`)
	if dataEnd < 0 {
		t.Fatal("data block end missing")
	}
	data := html[dataStart+len(`<script type="application/json" id="zeus-chart-data">`) : dataStart+dataEnd]
	if !strings.Contains(data, `"value":100`) || !strings.Contains(data, `"title":"测试图：三情景"`) {
		t.Fatalf("data block lost spec: %s", data)
	}
	scriptStart := strings.Index(html, "<script>")
	scriptEnd := strings.Index(html[scriptStart:], "</script>")
	fixed := html[scriptStart+len("<script>") : scriptStart+scriptEnd]
	if fixed != visualChartScript {
		t.Fatal("fixed script bytes differ")
	}
	for _, reportFact := range []string{"5998", "1,400,000", "测试图", `"value":100`} {
		if strings.Contains(fixed, reportFact) {
			t.Fatalf("fixed script contains report data %q", reportFact)
		}
	}
}

