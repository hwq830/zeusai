// Package reporttemplate is the single HTML template for reports: the App's WebView, the H5
// share page and (later) the PDF export all render through Render.
package reporttemplate

import (
	"bytes"
	_ "embed"
	"fmt"
	"html/template"
	"regexp"
	"strconv"
	"strings"

	"github.com/yuin/goldmark"
	"github.com/yuin/goldmark/extension"
)

//go:embed report.html.tmpl
var src string

// Connector results (mcp://…) are listed as sources but cannot be opened.
var page = template.Must(template.New("report").Funcs(template.FuncMap{
	"isWeb":  func(u string) bool { return strings.HasPrefix(u, "https://") || strings.HasPrefix(u, "http://") },
	"printf": fmt.Sprintf,
}).Parse(src))

var md = goldmark.New(goldmark.WithExtensions(extension.Table, extension.Strikethrough))

type Source struct {
	Index    int
	URL      string
	Title    string
	SiteName string
}

type Data struct {
	Title       string
	Summary     string
	Markdown    string // empty for summary-only shares
	DepthLabel  string
	SourceCount int
	CompletedAt string
	Sources     []Source
	// Share marks the public H5 page: it gets the AI label, the sharer line and the CTA.
	Share    bool
	SharedBy string // nickname, only when the sharer opted in
	AppURL   string // the CTA's link
	// Lang is the report's language, zh or en; it picks the page's own labels.
	Lang string
}

// Labels are the page's fixed texts in the report's language.
type Labels struct {
	HTMLLang, Sources, SourceCount, Disclaimer, CTA, AILabel, SharedBy string
}

var labels = map[string]Labels{
	"zh": {HTMLLang: "zh-CN", Sources: "来源", SourceCount: "%d 个来源", Disclaimer: "本报告由 AI 生成，内容仅供参考，请以原始来源为准。", CTA: "用 Zeus 生成你自己的报告", AILabel: "内容由 AI 生成", SharedBy: "来自 %s 的分享"},
	"en": {HTMLLang: "en", Sources: "Sources", SourceCount: "%d sources", Disclaimer: "This report was generated by AI and is for reference only. Please check the original sources.", CTA: "Create your own report with Zeus", AILabel: "AI-generated", SharedBy: "Shared by %s"},
}

// citeRe matches [n] citations; goldmark leaves unmatched [n] as literal text.
var citeRe = regexp.MustCompile(`\[(\d{1,3})\]`)

// Render produces the full HTML document. Raw HTML in the Markdown is not rendered
// (goldmark's default), so model output cannot inject markup.
func Render(d Data) ([]byte, error) {
	var body bytes.Buffer
	if d.Markdown != "" {
		if err := md.Convert([]byte(d.Markdown), &body); err != nil {
			return nil, err
		}
	}
	valid := map[int]bool{}
	for _, s := range d.Sources {
		valid[s.Index] = true
	}
	linked := citeRe.ReplaceAllFunc(body.Bytes(), func(m []byte) []byte {
		n, _ := strconv.Atoi(string(m[1 : len(m)-1]))
		if !valid[n] {
			return m
		}
		return []byte(`<sup class="cite"><a href="#src-` + strconv.Itoa(n) + `">` + strconv.Itoa(n) + `</a></sup>`)
	})
	var out bytes.Buffer
	l, ok := labels[d.Lang]
	if !ok {
		l = labels["zh"]
	}
	err := page.Execute(&out, struct {
		Data
		L    Labels
		Body template.HTML
	}{d, l, template.HTML(linked)}) // #nosec G203 -- goldmark output with raw HTML disabled
	return out.Bytes(), err
}
