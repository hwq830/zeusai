// Package briefingtemplate is the single HTML template for briefings: the App's preview, the
// H5 share page and the PDF export all render through Render.
package briefingtemplate

import (
	"bytes"
	_ "embed"
	"fmt"
	"html/template"
	"strings"

	"github.com/yuin/goldmark"
)

//go:embed briefing.html.tmpl
var src string

var page = template.Must(template.New("briefing").Funcs(template.FuncMap{
	"isWeb":  func(u string) bool { return strings.HasPrefix(u, "https://") || strings.HasPrefix(u, "http://") },
	"printf": fmt.Sprintf,
}).Parse(src))

var md = goldmark.New()

type Source struct {
	URL      string
	Title    string
	SiteName string
}

type Item struct {
	ID      string
	Title   string
	Summary string // simple Markdown; empty in summary-only shares
	Sources []Source
}

type Section struct {
	Title string
	Items []Item
}

type Data struct {
	Title    string
	Date     string // 2006-01-02
	Headline string
	Sections []Section
	// Share marks the public H5 page: it gets the AI label, the sharer line and the CTA.
	Share    bool
	SharedBy string // nickname, only when the sharer opted in
	CTAURL   string
	// Lang is the briefing's language, zh, zh-Hant or en; it picks the page's own labels.
	Lang string
}

// Labels are the page's fixed texts in the briefing's language.
type Labels struct {
	HTMLLang, AILabel, SharedBy, ItemCount, Disclaimer, CTA string
}

var labels = map[string]Labels{
	"zh": {HTMLLang: "zh-CN", AILabel: "内容由 AI 生成", SharedBy: "来自 %s 的分享", ItemCount: "%d 条",
		Disclaimer: "本简报由 AI 根据公开信息生成，内容仅供参考，请以原始来源为准。", CTA: "用同款模板生成我的简报"},
	"zh-Hant": {HTMLLang: "zh-Hant", AILabel: "內容由 AI 生成", SharedBy: "來自 %s 的分享", ItemCount: "%d 條",
		Disclaimer: "本簡報由 AI 根據公開資訊生成，內容僅供參考，請以原始來源為準。", CTA: "用同款模板生成我的簡報"},
	"en": {HTMLLang: "en", AILabel: "AI-generated", SharedBy: "Shared by %s", ItemCount: "%d items",
		Disclaimer: "This briefing was generated by AI from public sources and is for reference only. Please check the original sources.",
		CTA:        "Get this briefing for yourself"},
}

type renderItem struct {
	Item
	Body template.HTML
}

type renderSection struct {
	Title string
	Items []renderItem
}

// Render produces the full HTML document. Raw HTML in item summaries is not rendered
// (goldmark's default), so model output cannot inject markup.
func Render(d Data) ([]byte, error) {
	l, ok := labels[d.Lang]
	if !ok {
		l = labels["zh"]
	}
	secs := make([]renderSection, 0, len(d.Sections))
	n := 0
	for _, s := range d.Sections {
		rs := renderSection{Title: s.Title}
		for _, it := range s.Items {
			var body bytes.Buffer
			if it.Summary != "" {
				if err := md.Convert([]byte(it.Summary), &body); err != nil {
					return nil, err
				}
			}
			rs.Items = append(rs.Items, renderItem{Item: it, Body: template.HTML(body.String())}) // #nosec G203 -- goldmark output with raw HTML disabled
			n++
		}
		secs = append(secs, rs)
	}
	var out bytes.Buffer
	err := page.Execute(&out, struct {
		Data
		L         Labels
		Sections  []renderSection
		ItemCount int
	}{d, l, secs, n})
	return out.Bytes(), err
}
