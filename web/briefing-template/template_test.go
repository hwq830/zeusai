package briefingtemplate

import (
	"strings"
	"testing"
)

func TestRender(t *testing.T) {
	out, err := Render(Data{
		Title: "科技早报 <x>", Date: "2026-10-26", Headline: "今天三件事",
		Sections: []Section{{Title: "公司动态", Items: []Item{
			{ID: "i1", Title: "发布会", Summary: "**新品**发布。<script>alert(1)</script>",
				Sources: []Source{{URL: "https://a.example/1", Title: "原文", SiteName: "A 站"}, {URL: "mcp://amap/x", Title: "高德地图"}}},
		}}},
		Share: true, SharedBy: "小明", CTAURL: "https://zeus.example.com/s/t/go",
	})
	if err != nil {
		t.Fatal(err)
	}
	html := string(out)
	for _, want := range []string{"<h1>科技早报 &lt;x&gt;</h1>", "内容由 AI 生成", "来自 小明 的分享", "1 条",
		"<strong>新品</strong>", `<a href="https://a.example/1"`, "高德地图", "用同款模板生成我的简报", `content="noindex`} {
		if !strings.Contains(html, want) {
			t.Errorf("missing %q", want)
		}
	}
	if strings.Contains(html, "<script>alert") || strings.Contains(html, "ZgotmplZ") {
		t.Error("raw HTML must not be rendered and connector sources must not be links")
	}
}

func TestRenderPrivateCopy(t *testing.T) {
	out, err := Render(Data{Title: "Morning", Lang: "en", Sections: []Section{{Title: "News", Items: []Item{{ID: "a", Title: "One"}}}}})
	if err != nil {
		t.Fatal(err)
	}
	html := string(out)
	for _, want := range []string{`<html lang="en">`, "1 items", "generated by AI"} {
		if !strings.Contains(html, want) {
			t.Errorf("missing %q", want)
		}
	}
	if strings.Contains(html, "AI-generated</div>") || strings.Contains(html, `class="cta"`) || strings.Contains(html, "noindex") {
		t.Error("the App / PDF copy has no share chrome")
	}
}
